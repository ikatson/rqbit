#!/usr/bin/env python3
"""Generates the BEP 52 (BitTorrent v2) test fixtures in this directory with libtorrent.

    <venv with libtorrent 2.1>/bin/python make_fixtures.py

For each fixture it writes `<name>.torrent` and `<name>.json`, the latter holding what libtorrent
reports about the torrent (info hashes, piece count, file layout including padding files) for the
tests to compare against.

The file contents are not committed: they are generated by `content()`, which the tests reimplement
(`bep52_fixture_content` in the Rust tests) so they can hash the real data.
"""

import json
import os
import tempfile

import libtorrent as lt

HERE = os.path.dirname(os.path.abspath(__file__))
PIECE_LENGTH = 64 * 1024

# Relative path within the torrent, length. Covers: a file smaller than a piece and smaller than a
# block, one smaller than a piece with a block count that is not a power of two, an exact multiple
# of the piece length, nested directories, an empty file, non-ASCII names, and a file whose piece
# layer is padded to a power of two.
MULTI_FILES = [
    ("a/small.bin", 5_000),
    ("a/three_blocks.bin", 40_000),
    ("a/exact.bin", 2 * PIECE_LENGTH),
    ("a/b/c/nested.bin", 300_000),
    ("empty.txt", 0),
    ("ünïcødé/日本語.bin", 70_000),
    ("z_big.bin", 1_100_000),
]

SINGLE_FILE = ("single.bin", 200_000)


def content(path, length):
    """Deterministic content of the file at `path` (relative to the torrent root, "/"-separated):
    the top bytes of a 32-bit LCG seeded with the FNV-1a hash of the UTF-8 path."""
    state = 0x811C9DC5
    for b in path.encode("utf-8"):
        state = ((state ^ b) * 0x01000193) & 0xFFFFFFFF
    out = bytearray(length)
    for i in range(length):
        state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
        out[i] = state >> 24
    return bytes(out)


def write_files(root, files):
    for path, length in files:
        full = os.path.join(root, *path.split("/"))
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "wb") as f:
            f.write(content(path, length))


def make(name, content_path, flags):
    fs = lt.file_storage()
    lt.add_files(fs, content_path)
    ct = lt.create_torrent(fs, PIECE_LENGTH, flags)
    ct.set_creator("libtorrent " + lt.__version__)
    ct.set_creation_date(0)
    lt.set_piece_hashes(ct, os.path.dirname(content_path))
    data = lt.bencode(ct.generate())
    with open(os.path.join(HERE, name + ".torrent"), "wb") as f:
        f.write(data)

    ti = lt.torrent_info(lt.bdecode(data))
    hashes = ti.info_hashes()
    files = ti.files()
    prefix = files.name() + "/"
    layout = []
    for i in range(files.num_files()):
        path = files.file_path(i).replace(os.sep, "/")
        if path.startswith(prefix):
            path = path[len(prefix):]
        layout.append(
            {
                "path": path,
                "size": files.file_size(i),
                "offset": files.file_offset(i),
                "pad": bool(files.file_flags(i) & lt.file_storage.flag_pad_file),
            }
        )
    expected = {
        "info_hash_v1": str(hashes.v1) if hashes.has_v1() else None,
        "info_hash_v2": str(hashes.v2) if hashes.has_v2() else None,
        "piece_length": ti.piece_length(),
        "num_pieces": ti.num_pieces(),
        "total_size": ti.total_size(),
        "files": layout,
    }
    with open(os.path.join(HERE, name + ".json"), "w", encoding="utf-8") as f:
        json.dump(expected, f, indent=1, ensure_ascii=False)
        f.write("\n")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        multi = os.path.join(tmp, "multi")
        write_files(multi, MULTI_FILES)
        single = os.path.join(tmp, SINGLE_FILE[0])
        write_files(tmp, [SINGLE_FILE])

        make("v2_multi", multi, lt.create_torrent.v2_only)
        make("hybrid_multi", multi, 0)
        make("v2_single", single, lt.create_torrent.v2_only)
        make("hybrid_single", single, 0)


if __name__ == "__main__":
    main()
